const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const usage = {};
vm.createContext(usage);
vm.runInContext(fs.readFileSync('plasma/com.github.agentusage.panel/contents/code/usage.js', 'utf8'), usage);
assert.equal(usage.percent(null), '--');
assert.equal(usage.percent({utilization: 0}), '0%');
assert.equal(usage.percent({utilization: .429}), '42%');
assert.equal(usage.percent({utilization: NaN}), '--');
assert.equal(usage.stale(null, 1000), true);
assert.equal(usage.stale({updated_at: 1000, stale_after: 150}, 1150), false);
assert.equal(usage.stale({updated_at: 1000, stale_after: 150}, 1151), true);
assert.equal(usage.providers(null, true, true).length, 2);
assert.equal(usage.providers(null, false, true)[0].id, 'codex');
assert.equal(usage.providers(null, false, false).length, 0);
assert.equal(usage.severity({session: {utilization: .92}, weekly: null}, [.9, .75]), 2);
assert.equal(usage.severity({session: null, weekly: null}, [.75, .9]), 0);
assert.equal(usage.resetText({reset: 1120}, 1000), 'Resets in 2m');
assert.equal(usage.resetText({reset: 1000}, 1000), 'Resets soon');
assert.equal(usage.resetText({reset: 1000 + 3 * 3600 + 300}, 1000), 'Resets in 3h 5m');
assert.equal(usage.forecastText({reset: 9000, exhausts_at: 1000 + 80 * 60}, 1000), 'Full in 1h 20m');
assert.equal(usage.forecastText({reset: 9000, exhausts_at: 900}, 1000), '');
assert.equal(usage.forecastText({reset: 9000}, 1000), '');
assert.equal(usage.forecastText(null, 1000), '');
var pacing = {session: {utilization: .3, exhausts_at: 5000}, weekly: null};
assert.equal(usage.severity(pacing, [.75, .9]), 0);
assert.equal(usage.severity(pacing, [.75, .9], 1000), 1);
assert.equal(usage.severity(pacing, [.75, .9], 6000), 0);
assert.equal(usage.severity({session: {utilization: .95, exhausts_at: 5000}, weekly: null}, [.75, .9], 1000), 2);
assert.equal(usage.validSnapshot({version: 2}), false);
assert.equal(usage.command("/tmp/user's $(touch bad)"), "'/tmp/user'\\''s $(touch bad)' --panel-snapshot");
console.log('Panel formatting, forecasts, stale/error states, provider visibility, and command quoting passed.');
